// Generates shared/countryPoints.ts: a label point for every country in world-atlas (50m),
// used to resolve team countries and to draw match arcs. Run: node scripts/gen-country-points.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoArea, geoCentroid } from 'd3-geo'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)))
const polygons110 = new Set(
  JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url))).objects.countries.geometries.map((g) => g.id),
)

const points = {}
for (const f of feature(topo, topo.objects.countries).features) {
  if (!f.id) continue // e.g. Kosovo and N. Cyprus have no ISO code; handled as extras below
  // Use the largest landmass so France isn't centred near French Guiana.
  let geom = f.geometry
  if (geom.type === 'MultiPolygon') {
    const biggest = geom.coordinates
      .map((c) => ({ type: 'Polygon', coordinates: c }))
      .sort((a, b) => geoArea(b) - geoArea(a))[0]
    geom = biggest
  }
  const [lng, lat] = geoCentroid({ type: 'Feature', geometry: geom, properties: {} })
  points[f.id] = {
    name: f.properties.name,
    lat: +lat.toFixed(2),
    lng: +lng.toFixed(2),
    // Polygon id on the 110m globe, when the country is large enough to be drawn there.
    ...(polygons110.has(f.id) ? { polygon: f.id } : {}),
  }
}

// Home nations and other football-only "countries" (sharing the UK polygon where relevant).
Object.assign(points, {
  'gb-eng': { name: 'England', lat: 52.6, lng: -1.5, polygon: '826' },
  'gb-sct': { name: 'Scotland', lat: 56.8, lng: -4.2, polygon: '826' },
  'gb-wls': { name: 'Wales', lat: 52.3, lng: -3.7, polygon: '826' },
  'gb-nir': { name: 'Northern Ireland', lat: 54.6, lng: -6.7, polygon: '826' },
  xk: { name: 'Kosovo', lat: 42.6, lng: 20.9 },
  gi: { name: 'Gibraltar', lat: 36.14, lng: -5.35 },
})

const body = JSON.stringify(points, null, 0).replace(/\},"/g, '},\n  "')
writeFileSync(
  new URL('../../shared/countryPoints.ts', import.meta.url),
  `// GENERATED by web/scripts/gen-country-points.mjs from world-atlas. Do not edit by hand.
export interface CountryPoint {
  name: string
  lat: number
  lng: number
  /** world-atlas 110m polygon id to highlight, if the country is drawn on the globe. */
  polygon?: string
}

export const COUNTRY_POINTS: Record<string, CountryPoint> = ${body.replace(/^\{/, '{\n  ')}
`,
)
console.log('countries:', Object.keys(points).length)
